import assert from 'node:assert/strict';
import { accountContact } from '../bot/user-contact.mjs';
import { createSession, activeSteps, handle, setAutomaticContact } from '../bot/dialog.mjs';
import { ticketText } from '../ticket.mjs';
import { parseUpdate } from '../bot/max-api.mjs';
assert.equal(parseUpdate({update_type:'message_callback',callback:{user:{user_id:123,first_name:'Анна',last_name:'Тест'}},message:{sender:{name:'Бот'}}}).userName,'Анна Тест');
assert.equal(accountContact({id:123,name:'Тест',username:'test_user'},{phone:'79001112233'}),'Телефон: +79001112233 · MAX: @test_user (ID: 123)');
assert.equal(accountContact({id:123,name:'Тест'}),'MAX: Тест (ID: 123)');
assert(!accountContact({id:123}).includes('undefined'));
const s=createSession({id:123,name:'Тест'});setAutomaticContact(s,accountContact(s.user));
assert(!activeSteps(s).some(x=>x.id==='contact'));
assert.equal(s.answers.contact,'MAX: Тест (ID: 123)');
handle(s,{type:'callback',payload:'edit:contact'});assert.equal(s.editing,null);
handle(s,{type:'callback',payload:'c:contact:0'});assert.equal(s.answers.contact,'MAX: Тест (ID: 123)');
const old=createSession({id:123,name:'Тест'});old.stepIndex=activeSteps(old).findIndex(x=>x.id==='contact');
assert.equal(setAutomaticContact(old,'MAX: Тест (ID: 123)'),true);
assert.equal(activeSteps(old)[old.stepIndex].id,'files');
const later=createSession({id:123});later.stepIndex=activeSteps(later).findIndex(x=>x.id==='files');
setAutomaticContact(later,'MAX: ID 123');assert.equal(activeSteps(later)[later.stepIndex].id,'files');
const editing=createSession({id:123});editing.editing='contact';setAutomaticContact(editing,'MAX: ID 123');assert.equal(editing.phase,'confirm');assert.equal(editing.editing,null);
assert(!ticketText({fields:{}}).includes('Контакт: undefined'));
console.log('Автоконтакт: телефон, MAX-профиль, отсутствие шага, запрет редактирования, миграция — OK');
